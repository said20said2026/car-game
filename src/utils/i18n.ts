const STORAGE_KEY = 'apex_pulse_language';

export function getSavedLanguage(): string {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
  } catch {}
  return 'en';
}

export function saveLanguage(code: string): void {
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {}
  const langObj = LANGUAGES.find((l) => l.code === code);
  if (langObj && typeof document !== 'undefined') {
    document.documentElement.lang = langObj.code;
    document.documentElement.dir = langObj.dir;
  }
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('language_changed', { detail: { code } }));
  }
}

/**
 * Triggers full page translation via Google Translate widget bridge and cookies
 */
export function applyGlobalTranslation(code: string): void {
  saveLanguage(code);

  const googleLangMap: Record<string, string> = {
    zh: 'zh-CN',
    he: 'iw',
  };
  const targetGoogleCode = googleLangMap[code] || code;

  // Manage googtrans cookie on all domain variations
  try {
    const host = window.location.hostname;
    const isLocal = host === 'localhost' || host === '127.0.0.1';
    const domainVariations = isLocal ? [''] : ['', `; domain=${host}`, `; domain=.${host}`];

    if (code === 'en') {
      domainVariations.forEach((d) => {
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/${d};`;
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;`;
      });
    } else {
      domainVariations.forEach((d) => {
        document.cookie = `googtrans=/auto/${targetGoogleCode}; expires=Fri, 31 Dec 2030 23:59:59 GMT; path=/${d};`;
        document.cookie = `googtrans=/en/${targetGoogleCode}; expires=Fri, 31 Dec 2030 23:59:59 GMT; path=/${d};`;
      });
    }
  } catch {}

  // Helper to trigger select combo
  const triggerCombo = (): boolean => {
    try {
      const selectEl = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
      if (!selectEl) return false;

      if (code === 'en') {
        const resetOpt = Array.from(selectEl.options).find(
          (o) => o.value === '' || o.value === 'en' || o.value === 'auto'
        );
        selectEl.value = resetOpt ? resetOpt.value : '';
      } else {
        selectEl.value = targetGoogleCode;
      }

      selectEl.dispatchEvent(new Event('change', { bubbles: true }));

      // Also trigger HTMLEvents for older engines
      try {
        const evt = document.createEvent('HTMLEvents');
        evt.initEvent('change', true, true);
        selectEl.dispatchEvent(evt);
      } catch {}

      return true;
    } catch {
      return false;
    }
  };

  // Immediate attempt
  if (!triggerCombo()) {
    // Retry polling until Google script finishes rendering the combo
    let attempts = 0;
    const interval = setInterval(() => {
      attempts++;
      if (triggerCombo() || attempts >= 40) {
        clearInterval(interval);
      }
    }, 150);
  }
}

